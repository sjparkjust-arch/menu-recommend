MENUS = list({item[0]: item for item in reversed(RAW_MENUS)}.values())
MENUS.reverse()

# 마스터 데이터는 MENUS에서 실제 쓰인 값만(빈 필터/미사용 코스 방지, 첫 등장 순서 유지).
CUISINES = list(dict.fromkeys(item[1] for item in MENUS))
COURSES = list(dict.fromkeys(item[2] for item in MENUS))


class Command(BaseCommand):
    help = '초기 마스터 데이터(요리종류/코스/알러지)와 확장 메뉴 시드(메인/사이드)를 넣는다.'

    @transaction.atomic
    def handle(self, *args, **options):
        cuisines = self._seed_master(Cuisine, CUISINES, '요리 종류')
        courses = self._seed_master(Course, COURSES, '코스')
        allergies = self._seed_master(Allergy, ALLERGIES, '알러지')

        menu_created = 0
        desc_filled = 0
        link_created = 0
        for name, cuisine_name, course_name, meal_time, allergy_names, description in MENUS:
            menu, created = Menu.objects.get_or_create(
                name=name,
                defaults={
                    'cuisine': cuisines[cuisine_name],
                    'course': courses[course_name],
                    'meal_time': meal_time,
                    'description': description,
                },
            )
            if created:
                menu_created += 1
            elif description and not menu.description:
                # 기존 메뉴(좋아요/리뷰 붙은 것 포함)는 분류는 그대로 두고 설명만 백필.
                menu.description = description
                menu.save(update_fields=['description'])
                desc_filled += 1

            for allergy_name in allergy_names:
                _, link_is_new = MenuAllergy.objects.get_or_create(
                    menu=menu,
                    allergy=allergies[allergy_name],
                )
                if link_is_new:
                    link_created += 1

        self.stdout.write(self.style.SUCCESS(
            f'메뉴 {menu_created}개 신규 / 설명 백필 {desc_filled}개 / 전체 {Menu.objects.count()}개, '
            f'메뉴-알러지 연결 {link_created}건 신규 / 전체 {MenuAllergy.objects.count()}건'
        ))

    def _seed_master(self, model, names, label):
        objs = {}
        created = 0
        for name in names:
            obj, is_new = model.objects.get_or_create(name=name)
            objs[name] = obj
            if is_new:
                created += 1
        self.stdout.write(self.style.SUCCESS(
            f'{label}: {created}개 신규 / 전체 {len(names)}개'
        ))
        return objs
